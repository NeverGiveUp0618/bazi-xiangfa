"""把各篇「断之前先问清」汇总成 问诊单.md（各篇改了以后重跑本脚本，再跑 build.py）"""
import os, re
D = os.path.dirname(os.path.abspath(__file__))
ORDER = ['来意', '流年', '性格', '相貌', '官职', '考公', '职业', '进退', '财运', '公司经营', '合作', '感情', '婚姻', '合婚', '子女', '疾病', '意外', '寿元',
         '官司', '房产', '学业', '出行', '父母', '兄弟朋友', '小人是非', '失物', '玄学', '化解', '人生年龄', '层次']
out = ['# 断事图 · 问诊单：见客人之前要问清的事（各篇汇总）', '',
       '> 这一页由各篇末尾的「**断之前先问清**」自动汇总而成，内容以各篇为准。',
       '> **用法**：先按「来意」篇判断他为什么来，再翻到这里对应的一节，把表里的问题过一遍。',
       '', '## 通用（每一盘都问）', '',
       '| 先问 | 为什么 |', '|---|---|',
       '| **出生时间准不准、在哪出生** | 交节、子时、换气要排两个盘；「大山里应蛇咬，城市里应车祸」 |',
       '| **问自己还是替人问** | 盘是被问的人的，来意是来问的人的（「来意」篇） |',
       '| **多大年纪、在哪个城市** | 年龄尺、地域尺（「人生年龄」「层次」篇） |',
       '| **现在的大概情况** | 「八字即生活：断出来跟生活不符就是错了」〔小任 · 初中级第7课〕 |', '']
n = 0
for name in ORDER:
    p = os.path.join(D, name + '.md')
    if not os.path.exists(p):
        continue
    t = open(p, encoding='utf-8').read()
    m = re.search(r'^## [一二三四五六七八九十]+、断之前先问清\n(.*?)(?=^## |\Z)', t, re.S | re.M)
    if not m:
        continue
    body = m.group(1).strip()
    out += ['## ' + name, '', body, '']
    n += 1
open(os.path.join(D, '问诊单.md'), 'w', encoding='utf-8').write('\n'.join(out))
print('问诊单.md 汇总了', n, '篇')
